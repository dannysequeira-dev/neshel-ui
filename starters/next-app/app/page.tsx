import {
  Button,
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
  Dialog,
  DialogClose,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "@neshel-ui/components";
import { Container, Grid, Stack } from "@neshel-ui/layout";
import { Heading, Paragraph } from "@neshel-ui/typography";
import { cookies } from "next/headers";
import { ThemeSwitcher } from "./theme-switcher";

const cards = ["Server Components", "Custom breakpoints", "Named themes", "Accessible overlays"];

/**
 * A Server Component page. Layout, typography, Button and Card render on the server; Dialog and
 * Select are client components inside the package — no "use client" needed here.
 */
export default async function Home() {
  const theme = (await cookies()).get("theme")?.value ?? "system";
  return (
    <Container size="lg" gutter={{ base: "4", tablet: "8" }} className="py-12">
      <Stack space={{ base: "8", laptop: "12" }}>
        <Stack space="3">
          <Heading as="h1" size={{ base: "2xl", tablet: "4xl", wide: "5xl" }}>
            Hello, Neshel-UI on Next.js
          </Heading>
          <Paragraph tone="muted" measure="comfortable">
            Breakpoints here are phone, phoneXL, tablet, laptop, desktop and wide, configured in
            neshel.config.ts and generated by the neshel CLI.
          </Paragraph>
        </Stack>

        <ThemeSwitcher initial={theme} />

        <Grid columns={{ base: 1, phoneXL: 2, laptop: 4 }} space="4">
          {cards.map((title) => (
            <Card key={title} as="article">
              <CardHeader>
                <CardTitle as="h2">{title}</CardTitle>
                <CardDescription>Rendered on the server.</CardDescription>
              </CardHeader>
              <CardContent>
                <Paragraph size="sm" tone="muted">
                  Resize the window to see the columns change at your breakpoints.
                </Paragraph>
              </CardContent>
            </Card>
          ))}
        </Grid>

        <Dialog>
          <DialogTrigger asChild>
            <Button size={{ base: "md", laptop: "lg" }}>Open a dialog</Button>
          </DialogTrigger>
          <DialogContent>
            <DialogHeader>
              <DialogTitle>Hydrated on the client</DialogTitle>
              <DialogDescription>
                The dialog keeps the page theme across its portal.
              </DialogDescription>
            </DialogHeader>
            <DialogFooter>
              <DialogClose asChild>
                <Button>Close</Button>
              </DialogClose>
            </DialogFooter>
          </DialogContent>
        </Dialog>
      </Stack>
    </Container>
  );
}
