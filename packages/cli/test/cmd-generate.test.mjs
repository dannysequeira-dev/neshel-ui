// `neshel generate`: writing, idempotence, --check, output rules, I/O failures, determinism.
import assert from "node:assert/strict";
import { readFileSync, statSync, utimesSync, writeFileSync } from "node:fs";
import test from "node:test";
import { config, neshel, project } from "./helpers.mjs";

const fixture = (name) => readFileSync(new URL(`fixtures/${name}`, import.meta.url), "utf8");

export const GOLDEN_CONFIGS = {
  "golden-minimal.css": {},
  "golden-branded.css": {
    themes: {
      light: {
        colors: { primary: "#1D3F73", accent: "oklch(0.74 0.11 80)", accentForeground: "#071936" },
      },
      dark: { colors: { primary: "#a9c2ee" } },
      sepia: { extends: "light", colors: { background: "#f4ecd8", foreground: "#2b2118" } },
      "night-owl": { extends: "dark", colors: { background: "#000814" } },
    },
    radius: { base: "0.5rem", lg: "1rem" },
    spacing: { unit: "4px" },
    typography: {
      families: {
        body: ["Source Sans 3", "ui-sans-serif", "sans-serif"],
        mono: "Fira Code, monospace",
      },
    },
    focus: { width: "3px" },
  },
  "golden-rgb-hsl.css": {
    themes: {
      light: { colors: { background: "rgb(250, 248, 245)", border: "hsl(30 20% 85% / 0.6)" } },
    },
  },
};

test("writes the default output next to the config and reports it", (t) => {
  const p = project({ "neshel.config.mjs": config({}) });
  t.after(p.cleanup);
  const result = neshel(["generate"], p.dir);
  assert.equal(result.status, 0, result.stderr);
  assert.match(
    result.stdout,
    /^neshel: wrote neshel\.generated\.css \(2 themes, 0 warnings\)\.\n$/,
  );
  const css = readFileSync(p.path("neshel.generated.css"), "utf8");
  assert.match(
    css,
    /^\/\* Generated by "neshel generate" from neshel\.config\.mjs \(config schema 1\); do not edit\. \*\/\n\n@layer neshel\.defaults, neshel\.config;\n\n@layer neshel\.config \{/,
  );
  assert.ok(!css.includes(p.dir), "no absolute paths in the output");
});

test("golden outputs are byte-identical (SC-003)", (t) => {
  for (const [golden, input] of Object.entries(GOLDEN_CONFIGS)) {
    const p = project({ "neshel.config.mjs": config(input) });
    t.after(p.cleanup);
    const result = neshel(["generate"], p.dir);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(readFileSync(p.path("neshel.generated.css"), "utf8"), fixture(golden), golden);
  }
});

test("unchanged output is not rewritten (mtime preserved)", (t) => {
  const p = project({ "neshel.config.mjs": config({}) });
  t.after(p.cleanup);
  assert.equal(neshel(["generate"], p.dir).status, 0);
  const file = p.path("neshel.generated.css");
  const past = new Date("2020-01-01T00:00:00Z");
  utimesSync(file, past, past);
  const second = neshel(["generate"], p.dir);
  assert.equal(second.status, 0);
  assert.match(second.stdout, /unchanged neshel\.generated\.css/);
  assert.equal(statSync(file).mtime.getTime(), past.getTime());
});

test("--check: fresh 0, stale 4, missing 4; never writes", (t) => {
  const p = project({ "neshel.config.mjs": config({}) });
  t.after(p.cleanup);
  const missing = neshel(["generate", "--check"], p.dir);
  assert.equal(missing.status, 4);
  assert.match(missing.stdout, /is missing/);
  assert.equal(neshel(["generate"], p.dir).status, 0);
  assert.equal(neshel(["generate", "--check"], p.dir).status, 0);
  writeFileSync(p.path("neshel.generated.css"), "/* edited */\n");
  const stale = neshel(["generate", "--check"], p.dir);
  assert.equal(stale.status, 4);
  assert.match(stale.stdout, /out of date/);
  assert.equal(readFileSync(p.path("neshel.generated.css"), "utf8"), "/* edited */\n");
});

test("output resolution: --out from cwd, config output from the config directory", (t) => {
  const p = project({ "theme/neshel.config.mjs": config({ output: "../src/styles/neshel.css" }) });
  t.after(p.cleanup);
  const fromConfig = neshel(["generate", "--config", "theme/neshel.config.mjs"], p.dir);
  assert.equal(fromConfig.status, 0, fromConfig.stderr);
  assert.match(fromConfig.stdout, /wrote src\/styles\/neshel\.css/);
  const fromFlag = neshel(
    ["generate", "--config", "theme/neshel.config.mjs", "--out", "out dir ñ/x.css"],
    p.dir,
  );
  assert.equal(fromFlag.status, 0, fromFlag.stderr);
  assert.match(fromFlag.stdout, /wrote out dir ñ\/x\.css/);
  assert.ok(readFileSync(p.path("out dir ñ/x.css"), "utf8").includes("@layer neshel.config"));
});

test("rejected --out paths exit 2; the same via config output exit 1", (t) => {
  const p = project({ "neshel.config.mjs": config({}), "existing.css/keep.txt": "" });
  t.after(p.cleanup);
  for (const out of ["x.txt", "node_modules/a.css", "existing.css", "neshel.config.mjs"]) {
    const result = neshel(["generate", "--out", out], p.dir);
    assert.equal(result.status, 2, out);
    assert.match(result.stderr, /--out /, out);
  }
  const q = project({ "neshel.config.mjs": config({ output: "node_modules/a.css" }) });
  t.after(q.cleanup);
  assert.equal(neshel(["generate"], q.dir).status, 1);
});

test("validation errors and strict contrast write nothing", (t) => {
  const p = project({
    "neshel.config.mjs": config({ themes: { light: { colors: { accentForeground: "#6b5a3c" } } } }),
  });
  t.after(p.cleanup);
  const strict = neshel(["generate", "--strict"], p.dir);
  assert.equal(strict.status, 1);
  assert.throws(() => statSync(p.path("neshel.generated.css")));
  const warn = neshel(["generate"], p.dir);
  assert.equal(warn.status, 0);
  assert.match(warn.stdout, /1 warning/);
});

test("I/O failure exits 5 and leaves the previous output intact", (t) => {
  const p = project({ "neshel.config.mjs": config({}), blocker: "a file, not a directory" });
  t.after(p.cleanup);
  const result = neshel(["generate", "--out", "blocker/out.css"], p.dir);
  assert.equal(result.status, 5);
  assert.match(result.stderr, /^neshel: loaded neshel\.config\.mjs\nneshel: /);
  assert.equal(readFileSync(p.path("blocker"), "utf8"), "a file, not a directory");
});
