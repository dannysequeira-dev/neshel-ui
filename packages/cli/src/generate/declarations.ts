// Generated TypeScript declarations: breakpoint registry augmentation (contracts/breakpoints.md §4).
import type { ResolvedBreakpoints } from "../breakpoints.js";

/** First line of every generated declarations file; used to recognise Neshel-owned files. */
export const DECLARATIONS_MARKER = '// Generated by "neshel generate"';

export function generateDeclarations(breakpoints: ResolvedBreakpoints, configName: string): string {
  if (/[\r\n]/.test(configName)) throw new Error("config name must be a single line");
  const names = breakpoints.list.map((bp) => JSON.stringify(bp.name)).join(" | ");
  return `${DECLARATIONS_MARKER} from ${configName}; do not edit.
// Add this file to your TypeScript project ("include" or "files" in tsconfig.json).
export {};

declare module "@neshel-ui/config" {
  interface BreakpointRegistry {
    readonly names: ${names};
  }
}
`;
}

/** Whether existing file content was written by `neshel generate`. */
export function isGeneratedDeclarations(content: string): boolean {
  return content.startsWith(DECLARATIONS_MARKER);
}
